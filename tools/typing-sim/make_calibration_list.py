"""Builds the calibration typing test: a set of base words, each typed several times, in a fixed
shuffled order.

Repeats are the point. One badly typed word says little; the same word four times shows the habit.
The base set is:
- every word that has gone wrong for the user so far (their misreads are the cases that matter);
- common words picked greedily so every letter appears often, including as a word's first and last
  letter (swipe endpoints are the most exact points of a swipe), and in words that cross the
  keyboard halves (where two-thumb technique shows).

The order is shuffled with a fixed seed, so a second run on another day is directly comparable.

Usage: python3 make_calibration_list.py > ../../java/assets-tapswipe/typing-tests/calibration.txt
"""
import os
import random
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
VOCAB = os.path.join(HERE, "..", "..", "java", "assets", "futo-swipe", "hungry_jellyfish", "vocab.txt")
LEFT = set("qwertasdfgzxcvb")

# Words the user's typing tests got wrong on 2026-11-11 (both tests).
SEED = ["what", "want", "can", "work", "even", "out", "into", "then", "them", "take", "could", "any",
        "the", "about", "also", "back", "house"]
BASE = 42          # base words in total
REPEATS = 4        # times each base word appears
TARGET = 15        # letter occurrences across the whole test (after repeats)
RARE = {"j": 4, "q": 4, "x": 4, "z": 4}  # few common words hold these
EDGE = 2           # each letter as first, and as last letter, in the base set


def candidates():
    words = []
    for line in open(VOCAB):
        w = line.strip()
        if w.isalpha() and w.islower() and 2 <= len(w) <= 9:
            words.append(w)
        if len(words) >= 5000:
            break
    return words


def crosses(w):
    sides = ["L" if c in LEFT else "R" for c in w]
    return sum(a != b for a, b in zip(sides, sides[1:]))


def main():
    pool = [w for w in candidates() if w not in SEED]
    rank = {w: i for i, w in enumerate(pool)}
    base = list(SEED)
    have = Counter()
    first, last = Counter(), Counter()
    for w in base:
        have.update(w * REPEATS)
        first[w[0]] += 1
        last[w[-1]] += 1
    while len(base) < BASE:
        def gain(w):
            g = 0.0
            for c in set(w):
                t = RARE.get(c, TARGET)
                g += max(0, t - have[c]) / t * w.count(c)
            g += 1.5 * max(0, EDGE - first[w[0]]) / EDGE
            g += 1.5 * max(0, EDGE - last[w[-1]]) / EDGE
            g += 0.2 * min(crosses(w), 3)
            g -= rank[w] / 5000.0
            return g
        best = max(pool, key=gain)
        base.append(best)
        pool.remove(best)
        have.update(best * REPEATS)
        first[best[0]] += 1
        last[best[-1]] += 1
    words = [w for w in base for _ in range(REPEATS)]
    random.Random(20261111).shuffle(words)
    # Never the same word twice in a row: a repeat right away tests memory, not habit.
    for i in range(1, len(words)):
        if words[i] == words[i - 1]:
            for j in range(i + 1, len(words)):
                if words[j] != words[i] and words[j] != words[i - 1]:
                    words[i], words[j] = words[j], words[i]
                    break
    print("# Calibration: 42 words, 4 times each, fixed order. Type naturally, in your usual")
    print("# technique. Generated by tools/typing-sim/make_calibration_list.py.")
    for i in range(0, len(words), 8):
        print(" ".join(words[i:i + 8]))
    short = {c: have[c] for c in "abcdefghijklmnopqrstuvwxyz" if have[c] < RARE.get(c, TARGET)}
    sys.stderr.write(f"{len(words)} words from {len(base)} base words\n")
    sys.stderr.write(f"base: {' '.join(base)}\n")
    sys.stderr.write(f"letters under target: {short}\n")
    sys.stderr.write(f"min letter count: {min(have[c] for c in 'abcdefghijklmnopqrstuvwxyz')} "
                     f"({min('abcdefghijklmnopqrstuvwxyz', key=lambda c: have[c])})\n")


if __name__ == "__main__":
    main()
