"""Builds the calibration word list: common words chosen greedily so every letter is covered often,
as a word's first and last letter (swipe endpoints are the most exact points of a swipe), and in
words that cross between the keyboard halves (where two-thumb technique shows).

Usage: python3 make_calibration_list.py [N] > ../../java/assets-tapswipe/typing-tests/calibration.txt
"""
import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
VOCAB = os.path.join(HERE, "..", "..", "java", "assets", "futo-swipe", "hungry_jellyfish", "vocab.txt")
LEFT = set("qwertasdfgzxcvb")
N = int(sys.argv[1]) if len(sys.argv) > 1 else 120

TARGET_LETTER = 10   # occurrences of each letter anywhere
TARGET_EDGE = 3      # as first letter, and as last letter
RARE = set("jqxz")   # few common words hold these; ask for less


def candidates():
    words = []
    for line in open(VOCAB):
        w = line.strip()
        if w.isalpha() and w.islower() and 2 <= len(w) <= 10:
            words.append(w)
        if len(words) >= 4000:
            break
    return words


def crosses(w):
    sides = ["L" if c in LEFT else "R" for c in w]
    return sum(a != b for a, b in zip(sides, sides[1:]))


def main():
    pool = candidates()
    rank = {w: i for i, w in enumerate(pool)}
    have, first, last = Counter(), Counter(), Counter()
    chosen = []
    while len(chosen) < N and pool:
        def gain(w):
            g = 0.0
            for c in w:
                t = TARGET_LETTER // 3 if c in RARE else TARGET_LETTER
                g += max(0, t - have[c]) / t
            t = 1 if w[0] in RARE else TARGET_EDGE
            g += 2.0 * max(0, t - first[w[0]]) / t
            t = 1 if w[-1] in RARE else TARGET_EDGE
            g += 2.0 * max(0, t - last[w[-1]]) / t
            g += 0.3 * min(crosses(w), 3)
            g -= rank[w] / 4000.0  # prefer common words on ties
            return g
        best = max(pool, key=gain)
        if gain(best) <= 0.05:
            break
        chosen.append(best)
        pool.remove(best)
        have.update(best)
        first[best[0]] += 1
        last[best[-1]] += 1
    print("# Calibration list: every letter often, as first and last letter, and in words that")
    print("# cross the keyboard halves. Type naturally, in your usual technique. Generated by")
    print("# tools/typing-sim/make_calibration_list.py.")
    for i in range(0, len(chosen), 8):
        print(" ".join(chosen[i:i + 8]))
    short = [c for c in "abcdefghijklmnopqrstuvwxyz" if have[c] < (3 if c in RARE else TARGET_LETTER)]
    sys.stderr.write(f"{len(chosen)} words; letters under target: {short}\n")
    sys.stderr.write(f"first-letter gaps: {[c for c in 'abcdefghijklmnopqrstuvwxyz' if first[c] == 0]}\n")
    sys.stderr.write(f"last-letter gaps: {[c for c in 'abcdefghijklmnopqrstuvwxyz' if last[c] == 0]}\n")


if __name__ == "__main__":
    main()
